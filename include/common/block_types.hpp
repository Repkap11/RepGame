// Which tool family speeds up survival mining of a block. Derived in
// tools/blocks_import.py from the block name (an optional "mineable" JSON
// key overrides) — see docs/blocks.md. MINEABLE_NONE means no tool helps.
typedef enum {
    MINEABLE_NONE = 0,
    MINEABLE_PICKAXE, // stone/mineral/metal-like
    MINEABLE_AXE,     // wood-like
    MINEABLE_SHOVEL,  // dirt/sand/gravel/snow-like
    MINEABLE_SHEARS,  // leaves/wool/carpet/vines
    MINEABLE_HOE,     // right-click soil tilling; no block is mined faster
} MineableClass;

typedef struct {
    BlockID id;
    TextureID textures[ NUM_FACES_IN_CUBE ];
    RenderOrder renderOrder;
    int no_light;
    bool casts_shadow;
    bool is_seethrough;
    struct {
        bool x;
        bool y;
        bool z;
    } hides_self;
    bool needs_place_on_any_solid[ NUM_FACES_IN_CUBE ];
    bool needs_place_on_solid_but_can_stack_on_self;
    bool can_float_on_water;
    bool rotate_on_placement;
    bool icon_is_isometric;
    int flows;
    // Fluid behavior (flows != 0): level is stored in BlockState::rotation
    // (3 bits, so flow_range <= FLUID_MAX_LEVEL == 7, see common/fluid.hpp).
    // 0 = source, 1..flow_range = flowing cells, one level per horizontal
    // block of distance. flow_slope is how far sideways-spread searches for
    // a drop (Minecraft: 4 water, 2 lava). forms_sources lets two adjacent
    // horizontal sources over a solid/source base create a new source.
    int flow_range;
    int flow_slope;
    bool forms_sources;
    struct {
        short x;
        short y;
        short z;
    } scale;
    struct {
        short x;
        short y;
        short z;
    } offset;
    struct {
        short x;
        short y;
        short z;
    } tex_offset;
    bool non_full_size;
    bool is_pickable;
    bool collides_with_player;
    // Ladders (and any future vines/scaffolding): while the player AABB
    // overlaps the cell, pressing forward into a blocked wall or jumping
    // climbs, sneak hangs, and descent is capped — see
    // Collision::on_climbable and process_movement (docs/player.md).
    bool climbable;
    // Edible cake (MC's bites property): right-click eats a 2px slice off
    // the +x edge; the bite count 0..CAKE_MAX_BITES lives in
    // BlockState::rotation (never a yaw — block_yaw masks it to 0) and the
    // cut face draws cake_inner. The bite past CAKE_MAX_BITES removes the
    // block.
    bool is_cake;
    // Whether the block is a full opaque cube for redstone purposes: solid
    // blocks can hold power (strong or weak), and dust can connect up over
    // them. Glass, leaves, slabs, and other transparent or non-full blocks —
    // plus pistons, which are opaque but must never transmit power — are
    // non-solid. Defaults to true, finalized in the render-order pass.
    bool is_solid;
    bool breaks_in_liquid;
    // Block type can exist inside a water cell (corals, seaweed, etc.). The
    // actual per-cell waterlogged state lives on BlockState::waterlogged.
    bool waterloggable;
    int initial_redstone_power;
    bool affected_by_redstone_power;
    bool transmits_redstone_power;
    bool can_be_placed_in;
    // Seconds to break by hand in survival mode. 0 breaks instantly,
    // negative means unbreakable (e.g. bedrock).
    float hardness;
    // Tool family that speeds up breaking (MineableClass). Derived, with a
    // per-block "mineable" JSON override; MINEABLE_NONE by default.
    unsigned char mineable;
    struct {
        bool can_mesh_x;
        bool can_mesh_y;
        bool can_mesh_z;
        bool is_seethrough_face[ NUM_FACES_IN_CUBE ];
        bool hides_self[ NUM_FACES_IN_CUBE ];
    } calculated;
    bool connects_to_redstone_dust;
    bool is_redstone_dust;
    bool is_torch;
    // Fences draw as a post plus rails that connect to neighbors; gates draw
    // a closed or open multi-box model (see fence_boxes/fence_gate_boxes in
    // block.cpp). Gates store their open state in rotation bit 2
    // (BLOCK_ROTATE_GATE_OPEN); the facing is rotation & 3.
    bool is_fence;
    bool is_fence_gate;
    // Stairs draw as 2-3 boxes (a half slab plus step boxes) whose inner /
    // outer corner shape is derived live from the 4 horizontal neighbors
    // (stairs_shape_derive in block.cpp) — MC's getStairsShape. rotation
    // bits 0-1 are the facing (the direction the stair descends toward the
    // viewer, 0=-z), bit 2 is the top/upside-down half
    // (BLOCK_ROTATE_STAIRS_TOP).
    bool is_stairs;
    // Derived (no JSON key): a half slab — a colliding bottom-aligned
    // half-height box over the whole footprint — which can also hang from
    // the cell top. Rotation bit 2 (BLOCK_ROTATE_SLAB_TOP) mirrors the def's
    // box into the top half; the yaw bits are unused so block_yaw masks the
    // whole rotation to 0.
    bool is_slab;
    // Cactus-style Java model: the cell emits three instances — a full-cell
    // box drawing only top and bottom, and two 14-wide boxes drawing only
    // their side quads, which sit 1px inside each cell edge and sample the
    // whole side tile (opaque interior = inset body, edge columns = spines
    // at the boundary). Top/bottom are culled against covering neighbors.
    // The block's own scale/offset then describes only the pick/collision
    // box (chunk.cpp phase 2 emits the mesh).
    bool spine_shell;
    // Doors are two-cell blocks: a lower half and an upper half (linked by
    // door_partner) whose 3px slab hitbox swings to an adjacent facing when
    // opened. Both halves store the current slab yaw in rotation bits 0-1 so
    // rendering, collision, raycast, selection and debris need no cross-cell
    // reads; the lower's bit 2 is the open flag, the upper's is hinge-right
    // (BLOCK_ROTATE_DOOR_FLAG). door_redstone_only doors (iron) ignore
    // right-click toggles.
    bool is_door;
    bool is_door_upper;
    bool door_redstone_only;
    BlockID door_partner;
    // Tall plants (tall grass) are two-cell blocks like doors but without
    // the door semantics: a lower half and an upper half linked by
    // tall_plant_partner, with exactly one half carrying
    // is_tall_plant_upper. Both halves are cross-quad foliage (no
    // collision, no toggle); breaking either pops the other through the
    // neighbour-update survive check.
    bool is_tall_plant_upper;
    BlockID tall_plant_partner;
    // Leaf variant pairing, like the partner fields above: natural
    // (generator-grown) leaves point at their player-placed twin via
    // persistent_variant; the persistent twin points back via
    // natural_variant. LAST_BLOCK_ID means "not part of a pair". The pair
    // shares face textures — they differ only in decay behaviour.
    BlockID persistent_variant;
    BlockID natural_variant;
    // Crop growth chains ("crop_next" in data/blocks): a stage block points
    // at the next stage; the mature stage leaves it LAST_BLOCK_ID. Random
    // ticks and bonemeal advance the chain.
    BlockID crop_next;
    // Derived (no JSON key): the block is a member of a crop_next chain —
    // it survives only on farmland and grows by stage.
    bool is_crop;
    // Derived (no JSON key): the block is a member of the "logs" item tag —
    // a trunk block that holds up nearby leaves for decay purposes.
    bool is_log;
    // Derived (no JSON key): the block is a member of the "flowers" item
    // tag — a bee breed food for types with MobTypeDef::breeds_with_flowers.
    bool is_flower;
    // Flood-fill light emitted by this block, 0-15 (torches 14, lava/lamps 15,
    // lit furnace 13, portal 11, redstone torch 7). Stored in the chunk's
    // light[] volume and sampled by the fragment shader — never baked into the
    // mesh, so light changes don't trigger remeshing.
    unsigned char emits_light;
    // Extra light levels lost when propagation enters this cell, on top of the
    // standard -1 per step (leaves 1: crossing a leaf costs 2 where glass
    // costs 1). 0 elsewhere. Absorbing cells are light-permeable (not
    // casts_shadow) but still cap the direct vertical skylight fill.
    unsigned char light_absorb;
    // Derived (no JSON key): a light-holding cell that never passes light
    // downward and caps the vertical skylight column — bottom-aligned
    // partial blocks (slabs, path). Set in the render-order pass, which
    // also clears casts_shadow so every light_opaque_id site treats the
    // cell as light-holding.
    bool blocks_light_down;
    // Blocks that emit full redstone power while "pressed": buttons (pressed by
    // right-click, time out) and pressure plates (pressed while stood on).
    // current_redstone_power > 0 means pressed, and also shrinks the rendered
    // thickness (see block_adjust_coord_based_on_state).
    bool is_button;
    bool is_pressure_plate;
    // Mechanism components (pistons, lamps): they activate when an adjacent
    // block is powered at all — powered blocks feed mechanisms without the
    // mechanism re-emitting power of its own, so their stored level is capped
    // at 1 in BlockNextToChangeEvent.
    bool is_redstone_mechanism;
    // Piston base: current_redstone_power > 0 means extended. rotation encodes
    // the head direction: 0=+z(front) 1=-x(left) 2=-z(back) 3=+x(right)
    // 4=+y(up) 5=-y(down).
    bool is_piston;
    bool is_sticky_piston;
    // Internal cell block placed in front of an extended piston. Raycast-
    // targetable via the is_piston_head special case in contains_block (the
    // pick/collision boxes are piston_head_boxes' plate + arm shaft; mining
    // retargets the base) — but is_pickable stays false so it stays out of
    // creative and drops nothing. Breaks automatically when its base is
    // removed.
    bool is_piston_head;
    // TNT: a redstone mechanism that ignites on a rising power edge — the
    // block leaves the world as a primed entity (PrimedTnt) and a
    // TntExplodeEvent lands when the fuse ends.
    bool is_tnt;
    // Inverse TNT: an is_tnt variant whose blast restores every block in the
    // radius to the terrain generator's output (MapGen::gen_block_id, CPU
    // only) instead of destroying them. Ignites/launches like regular TNT;
    // the primed entity renders this block's texture.
    bool is_inverse_tnt;
    // PistonEvent refuses to push/pull these (plus powered pistons, heads,
    // and unloaded LAST_BLOCK_ID cells, which are handled there).
    bool piston_immovable;
    // Gravity block (sand, gravel, concrete powder, anvils): an unsupported
    // cell becomes a FALLING BlockBodies entity that lands and rewrites the
    // block. See FallingBlockEvent / BlockBodies.
    bool falls_with_gravity;
    // Mass multiplier for body-vs-body collisions and blast impulse resistance
    // (anvils are heavier than sand). 1.0 for ordinary falling blocks.
    float fall_mass;
    TextureID icon_texture;

} Block;

// Keep in order to make save file backwards compatible
struct __attribute__( ( packed ) ) BlockState {
    BlockID id;
    unsigned char rotation;
    int current_redstone_power;
    BlockID display_id;
    // This cell also contains water: the block was placed/generated into a
    // water cell and the block type is waterloggable. Set by Chunk::set_block.
    unsigned char waterlogged;
};

