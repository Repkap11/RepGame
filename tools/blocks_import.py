def load_blocks():
    blocks = {}
    names = {}
    for path in sorted(glob.glob(os.path.join(BLOCKS_DIR, "*.json"))):
        fname = os.path.basename(path)
        with open(path) as f:
            try:
                b = json.load(f)
            except json.JSONDecodeError as e:
                fail("%s: %s" % (fname, e))
        unknown = set(b) - KNOWN_KEYS
        if unknown:
            fail("%s: unknown keys %s" % (fname, sorted(unknown)))
        bid = b.get("id")
        name = b.get("name")
        if not isinstance(bid, int) or not (0 <= bid < LAST_BLOCK_ID):
            fail("%s: bad id %r (need 0 <= id < %d)" % (fname, bid, LAST_BLOCK_ID))
        if bid == RESERVED_BLOCK_ID:
            fail("%s: id %d is the reserved legacy empty-slot sentinel" % (fname, RESERVED_BLOCK_ID))
        if not isinstance(name, str) or not re.match(r"^[A-Z][A-Z0-9_]*$", name):
            fail("%s: bad name %r" % (fname, name))
        if bid in blocks:
            fail("%s: duplicate id %d (also in %s)" % (fname, bid, blocks[bid]["_file"]))
        if name in names:
            fail("%s: duplicate name %s" % (fname, name))
        if fname != name.lower() + ".json":
            fail("%s: file name must be <name>.json (name is %s)" % (fname, name))
        if "render_order" in b and b["render_order"] not in RENDER_ORDERS:
            fail("%s: bad render_order %r" % (fname, b["render_order"]))
        for k in BOOL_FIELDS & set(b):
            if not isinstance(b[k], bool):
                fail("%s: %s must be a bool" % (fname, k))
        for k in VEC3_SHORT | VEC3_BOOL:
            if k in b and (not isinstance(b[k], list) or len(b[k]) != 3):
                fail("%s: %s must be a 3-element list" % (fname, k))
        if "needs_place_on_any_solid" in b:
            v = b["needs_place_on_any_solid"]
            if not isinstance(v, dict) or any(k not in FACE_KEYS for k in v):
                fail("%s: needs_place_on_any_solid must be a face-name dict" % fname)
        if "aliases" in b:
            if not isinstance(b["aliases"], list) or not all(re.match(r"^[A-Z][A-Z0-9_]*$", a) for a in b["aliases"]):
                fail("%s: bad aliases" % fname)
        if "creative" in b and not isinstance(b["creative"], bool):
            fail("%s: creative must be a bool" % fname)
        b["_file"] = fname
        blocks[bid] = b
        names[name] = bid
    apply_shape(blocks, names)
    return blocks


def resolve_faces(name, b):
    """JSON textures dict -> per-face texture name list (FACE_* order)."""
    tex = b.get("textures", {})
    unknown = set(tex) - (set(FACE_KEYS) | {"all", "side"})
    if unknown:
        fail("%s: unknown texture face keys %s" % (b["_file"], sorted(unknown)))
    for k, v in tex.items():
        if not isinstance(v, str):
            fail("%s: texture %s must be a name string" % (b["_file"], k))
    faces = {k: name for k in FACE_KEYS}
    if "all" in tex:
        faces = {k: tex["all"] for k in FACE_KEYS}
    if "side" in tex:
        for k in SIDE_FACES:
            faces[k] = tex["side"]
    for k in FACE_KEYS:
        if k in tex:
            faces[k] = tex[k]
    return [faces[k] for k in FACE_KEYS]


def resolve_image(name, meta):
    """Find the source image for a texture, apply frame crop + tint."""
    src = meta.get("source")
    candidates = []
    if src:
        if src.endswith((".png", ".tga")):
            candidates.append(os.path.join(BEDROCK_SAMPLES, src))
        elif "/" in src:
            # Resource-pack-relative path without extension (e.g.
            # textures/blocks/planks_birch).
            candidates += [
                os.path.join(BEDROCK_SAMPLES, src + ".png"),
                os.path.join(BEDROCK_SAMPLES, src + ".tga"),
            ]
        else:
            candidates += [
                os.path.join(TEXTURES_DIR, src + ".png"),
                os.path.join(BEDROCK_SAMPLES, "textures", "blocks", src + ".png"),
                os.path.join(BEDROCK_SAMPLES, "textures", "blocks", src + ".tga"),
                os.path.join(BEDROCK_SAMPLES, "textures", "items", src + ".png"),
            ]
    else:
        candidates = [
            os.path.join(TEXTURES_DIR, name + ".png"),
            os.path.join(BEDROCK_SAMPLES, "textures", "blocks", name + ".png"),
            os.path.join(BEDROCK_SAMPLES, "textures", "blocks", name + ".tga"),
            os.path.join(BEDROCK_SAMPLES, "textures", "items", name + ".png"),
        ]
    path = next((c for c in candidates if os.path.exists(c)), None)
    if not path:
        fail("texture %r: no image found (tried %s). If the source lives in "
             "bedrock-samples, run `make bedrock-samples` or set BEDROCK_SAMPLES" %
             (name, [os.path.relpath(c, ROOT) for c in candidates]))
    img = Image.open(path).convert("RGBA")
    frame = meta.get("frame", 0)
    if not isinstance(frame, int) or frame < 0:
        fail("texture %r: bad frame %r" % (name, frame))
    img = img.crop((0, frame * TILE, TILE, (frame + 1) * TILE))
    if img.size != (TILE, TILE):
        fail("texture %r (%s): not %dx%d after frame crop (is %s)" % (name, os.path.relpath(path, ROOT), TILE, TILE, img.size))
    tint = meta.get("tint")
    if tint is not None:
        if not re.match(r"^#[0-9a-fA-F]{6}$", tint):
            fail("texture %r: bad tint %r" % (name, tint))
        tr, tg, tb = int(tint[1:3], 16), int(tint[3:5], 16), int(tint[5:7], 16)
        r, g, b_, a = img.split()
        lut_r = [min(255, (i * tr) // 255) for i in range(256)]
        lut_g = [min(255, (i * tg) // 255) for i in range(256)]
        lut_b = [min(255, (i * tb) // 255) for i in range(256)]
        img = Image.merge("RGBA", (r.point(lut_r), g.point(lut_g), b_.point(lut_b), a))
    alpha = meta.get("alpha")
    if alpha is not None:
        if not isinstance(alpha, int) or not (0 <= alpha <= 255):
            fail("texture %r: bad alpha %r (need 0-255)" % (name, alpha))
        r, g, b_, a = img.split()
        img = Image.merge("RGBA", (r, g, b_, a.point(lambda v: alpha if v else 0)))
    return img


def main():
    if not os.path.isdir(BEDROCK_SAMPLES):
        fail("BEDROCK_SAMPLES %r does not exist - run `make bedrock-samples` "
             "or set BEDROCK_SAMPLES to a resource_pack directory" % BEDROCK_SAMPLES)
    blocks = load_blocks()

    tex_meta = {}
    if os.path.exists(TEXTURES_JSON):
        with open(TEXTURES_JSON) as f:
            tex_meta = json.load(f)
        for name, m in tex_meta.items():
            if not isinstance(m, dict):
                fail("textures.json: %r must map to an object" % name)
            unknown = set(m) - TEX_META_KEYS
            if unknown:
                fail("textures.json: %r has unknown keys %s" % (name, sorted(unknown)))

    # Resolve every block's faces + icon and collect the referenced textures.
    resolved = {}  # bid -> {"faces": [6 names], "icon": name}
    used = set()
    for bid, b in sorted(blocks.items()):
        name = b["name"].lower()
        faces = resolve_faces(name, b)
        # No explicit icon: the default isometric cube icon is drawn from the
        # faces; icon_texture just needs to be a real layer.
        icon = b.get("icon", faces[FACE_KEYS.index("top")])
        if "icon" in b and "icon_is_isometric" not in b:
            b["icon_is_isometric"] = False
        resolved[bid] = {"faces": faces, "icon": icon}
        used.update(faces)
        used.add(icon)
    for name, m in tex_meta.items():
        if m.get("keep"):
            used.add(name)

    # Resolve every texture once (frame/tint/alpha applied), then collapse
    # byte-identical tiles into a single layer. The canonical name is the
    # alphabetically first member; other names still get TEX_* defines.
    images = {}
    for name in sorted(used):
        images[name] = resolve_image(name, tex_meta.get(name, {}))

    # Silhouette (mask) shapes: the 4 side faces become generated
    # <face_tex>__<shape> tiles — the fully resolved face image (frame/tint/
    # alpha already applied) with masked-out pixels set to transparent black.
    # Top and bottom keep the plain material texture. The generated tiles
    # merge like any other byte-identical texture.
    side_idx = [FACE_KEYS.index(k) for k in SIDE_FACES]
    for bid, b in sorted(blocks.items()):
        shape = b.get("shape")
        if shape not in SHAPES["masks"]:
            continue
        mask = SHAPES["masks"][shape]
        faces = resolved[bid]["faces"]
        for i in side_idx:
            src = faces[i]
            mname = "%s__%s" % (src, shape)
            if mname not in images:
                img = images[src].copy()
                px = img.load()
                for r in range(TILE):
                    mrow = mask[r]
                    for c in range(TILE):
                        if mrow[c] == ".":
                            px[c, r] = (0, 0, 0, 0)
                images[mname] = img
            faces[i] = mname
            used.add(mname)

    canon_members = {}  # canonical name -> [member names]
    for name in sorted(images):
        key = images[name].tobytes()
        canon_members.setdefault(key, []).append(name)
    members = {}
    canonical = {}  # name -> canonical
    for names in canon_members.values():
        canon = min(names)
        members[canon] = names
        for n in names:
            canonical[n] = canon
    canonical_names = sorted(members)

    # Layer order: rotatable layers first (a layer is rotatable if ANY member
    # has random_rotate), then the rest; sorted by canonical name.
    rotatable_canon = sorted(
        c for c in canonical_names
        if any(tex_meta.get(n, {}).get("random_rotate") for n in members[c]))
    rest_canon = sorted(set(canonical_names) - set(rotatable_canon))
    layer_order = rotatable_canon + rest_canon
    layers = {}
    for i, canon in enumerate(layer_order):
        for n in members[canon]:
            layers[n] = i
    count = len(layer_order)
    merged_count = len(used) - count
    # Merged sets mixing rotatable and non-rotatable members: the non-rotatable
    # members now ride the rotatable layer — flag for review.
    mixed_rotatable = [(c, members[c]) for c in rotatable_canon
                       if not all(tex_meta.get(n, {}).get("random_rotate")
                                  for n in members[c])]
    if count > TEXTURE_COUNT_MAX:
        fail("TEXTURE_COUNT %d exceeds %d (GLES texture-array limit)" %
             (count, TEXTURE_COUNT_MAX))
    rows = math.ceil(count / ACROSS)

    # Pack the atlas.
    atlas = Image.new("RGBA", (ACROSS * TILE, rows * TILE), (0, 0, 0, 0))
    for i, canon in enumerate(layer_order):
        atlas.paste(images[canon], ((i % ACROSS) * TILE, (i // ACROSS) * TILE))
    atlas.save(OUT_PNG)

    # include/common/block_ids_gen.hpp
    out = [HEADER, "#pragma once\n\n", "typedef enum {\n"]
    for bid, b in sorted(blocks.items()):
        names = [b["name"]] + b.get("aliases", [])
        for n in names:
            out.append("    %s = %d,\n" % (n, bid))
    out.append("\n    LAST_BLOCK_ID = %d,\n" % LAST_BLOCK_ID)
    out.append("} BlockID;\n\n")
    # Bitset marking which ids have a definition; used to sanitize saved
    # inventory slots whose ids were freed (filler/texture-only) and never
    # redefined.
    out.append("#define BLOCK_DEFINED_BITS_LEN %d\n" % ((LAST_BLOCK_ID + 7) // 8))
    out.append("static const unsigned char BLOCK_DEFINED_BITS[BLOCK_DEFINED_BITS_LEN] = {\n")
    for i in range(0, LAST_BLOCK_ID, 8):
        byte = 0
        for bit in range(8):
            if i + bit in blocks:
                byte |= 1 << bit
        out.append("0x%02x," % byte)
    out.append("\n};\n")
    out.append("static inline int block_id_defined( unsigned int id ) {\n")
    out.append("    return id < (unsigned int)LAST_BLOCK_ID && ( BLOCK_DEFINED_BITS[ id >> 3 ] & ( 1u << ( id & 7 ) ) ) != 0;\n")
    out.append("}\n")
    with open(OUT_IDS, "w") as f:
        f.writelines(out)

    # include/common/texture_ids_gen.hpp — #define only, safe for the GLSL
    # preprocessor (gcc -E -I include).
    # src/common/block_names_gen.inc — name table, nullptr for undefined ids.
    out_names = os.path.join(OUT_DIR, "block_names_gen.inc") if OUT_DIR else \
        os.path.join(ROOT, "src", "common", "block_names_gen.inc")
    out = [HEADER]
    for bid in range(LAST_BLOCK_ID):
        b = blocks.get(bid)
        out.append('    "%s",\n' % b["name"] if b else "    nullptr,\n")
    with open(out_names, "w") as f:
        f.writelines(out)

    # src/common/texture_names_gen.inc — canonical name per layer.
    out_tnames = os.path.join(OUT_DIR, "texture_names_gen.inc") if OUT_DIR else \
        os.path.join(ROOT, "src", "common", "texture_names_gen.inc")
    out = [HEADER]
    for canon in layer_order:
        out.append('    "%s",\n' % canon)
    with open(out_tnames, "w") as f:
        f.writelines(out)

    out = [HEADER, "#ifndef REPGAME_TEXTURE_IDS_GEN_HPP\n#define REPGAME_TEXTURE_IDS_GEN_HPP\n\n"]
    for name in sorted(layers):
        canon = canonical[name]
        if canon != name:
            out.append("#define TEX_%s TEX_%s\n" % (name.upper(), canon.upper()))
        else:
            out.append("#define TEX_%s %d\n" % (name.upper(), layers[name]))
    out.append("\n#define TEXTURE_COUNT %d\n" % count)
    out.append("#define TEXTURE_ROTATABLE_COUNT %d\n" % len(rotatable_canon))
    out.append("#define BLOCK_TEXTURE_ATLAS_ROWS %d\n" % rows)
    out.append("\n#endif\n")
    with open(OUT_TEX, "w") as f:
        f.writelines(out)

    # src/common/block_definitions_gen.inc — all 6 textures + icon for every
    # block, then non-default fields.
    out = [HEADER]
    for bid in range(LAST_BLOCK_ID):
        b = blocks.get(bid)
        if b is None:
            out.append("\n// undefined (%d)\n" % bid)
            for face in FACE_KEYS:
                out.append("block_definitions[ %d ].textures[ %s ] = TEX_AIR;\n" % (bid, FACE_CONST[face]))
            out.append("block_definitions[ %d ].icon_texture = TEX_AIR;\n" % bid)
            out.append("block_definitions[ %d ].is_pickable = false;\n" % bid)
            continue
        r = resolved[bid]
        out.append("\n// %s (%d)\n" % (b["name"], bid))
        for face in FACE_KEYS:
            out.append("block_definitions[ %d ].textures[ %s ] = TEX_%s;\n" % (bid, FACE_CONST[face], r["faces"][FACE_KEYS.index(face)].upper()))
        out.append("block_definitions[ %d ].icon_texture = TEX_%s;\n" % (bid, r["icon"].upper()))
        for key in sorted(b):
            if key in {"_file", "id", "name", "aliases", "textures", "icon", "shape", "creative"}:
                continue
            val = b[key]
            prefix = "block_definitions[ %d ]." % bid
            if key == "render_order":
                out.append("%srenderOrder = RenderOrder_%s;\n" % (prefix, val))
            elif key == "needs_place_on_any_solid":
                for face in FACE_KEYS:
                    if val.get(face):
                        out.append("%sneeds_place_on_any_solid[ %s ] = true;\n" % (prefix, FACE_CONST[face]))
            elif key in VEC3_SHORT:
                out.append("%s%s = { %s };\n" % (prefix, key, ", ".join(str(int(x)) for x in val)))
            elif key in VEC3_BOOL:
                out.append("%s%s = { %s };\n" % (prefix, key, ", ".join("true" if x else "false" for x in val)))
            elif key in BOOL_FIELDS:
                out.append("%s%s = %s;\n" % (prefix, key, "true" if val else "false"))
            elif key in FLOAT_FIELDS:
                out.append("%s%s = %sf;\n" % (prefix, key, fmt_float(val)))
            else:
                out.append("%s%s = %s;\n" % (prefix, key, val))
    with open(OUT_INC, "w") as f:
        f.writelines(out)

    # include/common/creative_order_gen.hpp + human-readable report.
    kept_ids = set()
    if os.path.exists(KEPT_IDS_FILE):
        kept_ids = {int(l) for l in open(KEPT_IDS_FILE) if l.strip()}
    creative, hidden = compute_creative(blocks, resolved, kept_ids, layers)
    out_cre = os.path.join(OUT_DIR, "creative_order_gen.hpp") if OUT_DIR else \
        os.path.join(ROOT, "include", "common", "creative_order_gen.hpp")
    out = [HEADER, "#pragma once\n\n#include \"common/block_ids_gen.hpp\"\n\n"]
    out.append("#define CREATIVE_BLOCK_COUNT %d\n" % len(creative))
    out.append("static const BlockID CREATIVE_BLOCKS[CREATIVE_BLOCK_COUNT] = {\n")
    for bid in creative:
        out.append("    %s,\n" % blocks[bid]["name"])
    out.append("};\n")
    with open(out_cre, "w") as f:
        f.writelines(out)
    rep_lines = []
    for bid in creative:
        dups = ", ".join(blocks[h]["name"] for h in hidden.get(bid, []))
        mat, _dye = material_key(blocks[bid]["name"])
        rep_lines.append("%s\t%s\t%d\thidden duplicates: %s\n" %
                         (mat, blocks[bid]["name"], bid, dups or "-"))
    os.makedirs(os.path.dirname(CREATIVE_REPORT), exist_ok=True)
    with open(CREATIVE_REPORT, "w") as f:
        f.write("material\tname\tid\thidden duplicates\n")
        f.writelines(rep_lines)

    print("blocks_import: %d blocks, %d textures (%d rotatable), atlas %dx%d -> %s" %
          (len(blocks), count, len(rotatable_canon), atlas.width, atlas.height,
           ", ".join(os.path.relpath(p, ROOT) for p in (OUT_IDS, OUT_TEX, OUT_INC, OUT_PNG))))
    pickable = sum(1 for b in blocks.values() if b.get("is_pickable", True))
    hidden_n = sum(len(v) for v in hidden.values())
    print("blocks_import: creative %d listed of %d pickable (%d hidden duplicates) -> %s" %
          (len(creative), pickable, hidden_n, os.path.relpath(out_cre, ROOT)))
    if merged_count:
        print("blocks_import: %d textures merged into existing layers by identical pixels" % merged_count)
    for canon, names in mixed_rotatable:
        print("blocks_import: WARNING rotatable layer %s merges non-rotatable %s" %
              (canon, [n for n in names if not tex_meta.get(n, {}).get("random_rotate")]))


if __name__ == "__main__":
    main()
