def load_blocks():
    blocks = {}
    names = {}
    for path in sorted(glob.glob(os.path.join(BLOCKS_DIR, "*.json"))):
        fname = os.path.basename(path)
        with open(path) as f:
            try:
                b = json.load(f)
            except json.JSONDecodeError as e:
                fail("%s: %s" % (fname, e))
        unknown = set(b) - KNOWN_KEYS
        if unknown:
            fail("%s: unknown keys %s" % (fname, sorted(unknown)))
        bid = b.get("id")
        name = b.get("name")
        if not isinstance(bid, int) or not (0 <= bid < LAST_BLOCK_ID):
            fail("%s: bad id %r (need 0 <= id < %d)" % (fname, bid, LAST_BLOCK_ID))
        if bid == RESERVED_BLOCK_ID:
            fail("%s: id %d is the reserved legacy empty-slot sentinel" % (fname, RESERVED_BLOCK_ID))
        if not isinstance(name, str) or not re.match(r"^[A-Z][A-Z0-9_]*$", name):
            fail("%s: bad name %r" % (fname, name))
        if bid in blocks:
            fail("%s: duplicate id %d (also in %s)" % (fname, bid, blocks[bid]["_file"]))
        if name in names:
            fail("%s: duplicate name %s" % (fname, name))
        if fname != name.lower() + ".json":
            fail("%s: file name must be <name>.json (name is %s)" % (fname, name))
        if "render_order" in b and b["render_order"] not in RENDER_ORDERS:
            fail("%s: bad render_order %r" % (fname, b["render_order"]))
        for k in BOOL_FIELDS & set(b):
            if not isinstance(b[k], bool):
                fail("%s: %s must be a bool" % (fname, k))
        for k in VEC3_SHORT | VEC3_BOOL:
            if k in b and (not isinstance(b[k], list) or len(b[k]) != 3):
                fail("%s: %s must be a 3-element list" % (fname, k))
        if "needs_place_on_any_solid" in b:
            v = b["needs_place_on_any_solid"]
            if not isinstance(v, dict) or any(k not in FACE_KEYS for k in v):
                fail("%s: needs_place_on_any_solid must be a face-name dict" % fname)
        if "aliases" in b:
            if not isinstance(b["aliases"], list) or not all(re.match(r"^[A-Z][A-Z0-9_]*$", a) for a in b["aliases"]):
                fail("%s: bad aliases" % fname)
        if "creative" in b and not isinstance(b["creative"], bool):
            fail("%s: creative must be a bool" % fname)
        if "drops" in b:
            if not isinstance(b["drops"], list):
                fail("%s: drops must be a list" % fname)
            for d in b["drops"]:
                if not isinstance(d, dict) or set(d) - DROP_KEYS or "item" not in d:
                    fail("%s: bad drops entry %r (needs item/min/max/chance)" % (fname, d))
                if not isinstance(d["item"], str) or not re.match(r"^[A-Z][A-Z0-9_]*$", d["item"]):
                    fail("%s: drops item must be a block or item name" % fname)
                mn = d.get("min", 1)
                mx = d.get("max", 1)
                ch = d.get("chance", 1.0)
                if not isinstance(mn, int) or not isinstance(mx, int) or mn < 0 or mx < mn:
                    fail("%s: bad drops min/max %r/%r" % (fname, mn, mx))
                if not isinstance(ch, (int, float)) or not (0.0 < float(ch) <= 1.0):
                    fail("%s: bad drops chance %r (need 0 < chance <= 1)" % (fname, ch))
                d.setdefault("min", 1)
                d.setdefault("max", 1)
                d.setdefault("chance", 1.0)
            # Entries with chance < 1 are mutually exclusive alternatives
            # rolled as one cumulative draw — their chances must sum to <= 1.
            if sum(d["chance"] for d in b["drops"] if d["chance"] < 1.0) > 1.0 + 1e-9:
                fail("%s: chance < 1 drops must sum to <= 1.0" % fname)
        for k in BLOCK_REF_FIELDS & set(b):
            if not isinstance(b[k], str) or not re.match(r"^[A-Z][A-Z0-9_]*$", b[k]):
                fail("%s: %s must be a block name string" % (fname, k))
        b["_file"] = fname
        blocks[bid] = b
        names[name] = bid
    apply_shape(blocks, names)
    # door_partner links a door's two halves: the named block must exist,
    # point back, and carry the opposite is_door_upper flag.
    for bid, b in blocks.items():
        partner = b.get("door_partner")
        if partner is None:
            continue
        pbid = names.get(partner)
        if pbid is None:
            fail("%s: door_partner %s not found" % (b["_file"], partner))
        pb = blocks[pbid]
        if pb.get("door_partner") != b["name"]:
            fail("%s: door_partner %s does not point back" % (b["_file"], partner))
        if not (b.get("is_door") and pb.get("is_door")):
            fail("%s: door_partner %s is not a door" % (b["_file"], partner))
        if bool(b.get("is_door_upper")) == bool(pb.get("is_door_upper")):
            fail("%s: door pair %s/%s needs exactly one is_door_upper" % (b["_file"], b["name"], partner))
    return blocks


def load_items(block_names):
    """data/items/<name>.json — one file per pure (non-block) item. Ids live
    at ITEM_ID_BASE and above; a block id IS its block item."""
    items = {}
    names = {}
    for path in sorted(glob.glob(os.path.join(ITEMS_DIR, "*.json"))):
        fname = os.path.basename(path)
        with open(path) as f:
            try:
                it = json.load(f)
            except json.JSONDecodeError as e:
                fail("%s: %s" % (fname, e))
        unknown = set(it) - ITEM_KNOWN_KEYS
        if unknown:
            fail("%s: unknown keys %s" % (fname, sorted(unknown)))
        iid = it.get("id")
        name = it.get("name")
        if not isinstance(iid, int) or iid < ITEM_ID_BASE:
            fail("%s: bad id %r (need id >= %d)" % (fname, iid, ITEM_ID_BASE))
        if not isinstance(name, str) or not re.match(r"^[A-Z][A-Z0-9_]*$", name):
            fail("%s: bad name %r" % (fname, name))
        if iid in items:
            fail("%s: duplicate id %d (also in %s)" % (fname, iid, items[iid]["_file"]))
        if name in names:
            fail("%s: duplicate name %s" % (fname, name))
        if name in block_names:
            fail("%s: name %s collides with a block name" % (fname, name))
        if fname != name.lower() + ".json":
            fail("%s: file name must be <name>.json (name is %s)" % (fname, name))
        icon = it.get("icon")
        if not isinstance(icon, str):
            fail("%s: icon must be a texture name string" % fname)
        if "max_stack" in it:
            ms = it["max_stack"]
            if not isinstance(ms, int) or not (1 <= ms <= 127):
                fail("%s: bad max_stack %r (need 1-127)" % (fname, ms))
        if "aliases" in it:
            if not isinstance(it["aliases"], list) or not all(re.match(r"^[A-Z][A-Z0-9_]*$", a) for a in it["aliases"]):
                fail("%s: bad aliases" % fname)
        it["_file"] = fname
        items[iid] = it
        names[name] = iid
        for a in it.get("aliases", []):
            names[a] = iid
    if items and sorted(items) != list(range(ITEM_ID_BASE, ITEM_ID_BASE + len(items))):
        fail("item ids must be contiguous from %d" % ITEM_ID_BASE)
    return items, names


def load_item_tags(block_names, item_names):
    """data/item_tags.json: {"tag": ["BLOCK_OR_ITEM_NAME", ...]} used by
    recipe ingredients as "#tag"."""
    if not os.path.exists(ITEM_TAGS_JSON):
        return {}
    with open(ITEM_TAGS_JSON) as f:
        tags = json.load(f)
    if not isinstance(tags, dict):
        fail("item_tags.json: must be an object")
    for tag, members in tags.items():
        if not isinstance(tag, str) or not re.match(r"^[a-z][a-z0-9_]*$", tag):
            fail("item_tags.json: bad tag name %r" % tag)
        if not isinstance(members, list) or not members:
            fail("item_tags.json: tag %r must be a non-empty list" % tag)
        for m in members:
            if not isinstance(m, str) or (m not in block_names and m not in item_names):
                fail("item_tags.json: tag %r member %r is not a block or item name" % (tag, m))
    return tags


def load_recipes(tags, blocks, items):
    """data/recipes/*.json, sorted filename order. Returns a list of
    {"shaped": bool, "width", "height", "cells": [id list or None] *9,
    "result": id, "count": int}; a recipe has exactly one of "pattern"
    (shaped) or "ingredients" (shapeless)."""
    block_names = {b["name"]: bid for bid, b in blocks.items()}
    item_names = {it["name"]: iid for iid, it in items.items()}
    for b in blocks.values():
        for a in b.get("aliases", []):
            block_names.setdefault(a, b["id"])
    for it in items.values():
        for a in it.get("aliases", []):
            item_names.setdefault(a, it["id"])

    def resolve_name(name, what):
        iid = block_names.get(name)
        if iid is None:
            iid = item_names.get(name)
        if iid is None:
            fail("%s: %r is not a block or item name" % (what, name))
        return iid

    def ingredient_ids(ing, what):
        # <ing> := "NAME" | "#tag" | [ "NAME" | "#tag", ... ] -> option ids.
        if isinstance(ing, str):
            opts = [ing]
        elif isinstance(ing, list) and ing and all(isinstance(x, str) for x in ing):
            opts = ing
        else:
            fail("%s: bad ingredient %r" % (what, ing))
        ids = []
        for o in opts:
            if o.startswith("#"):
                tag = o[1:]
                if tag not in tags:
                    fail("%s: unknown item tag %r" % (what, o))
                ids.extend(resolve_name(m, what) for m in tags[tag])
            else:
                ids.append(resolve_name(o, what))
        seen = set()
        return [i for i in ids if not (i in seen or seen.add(i))]

    recipes = []
    for path in sorted(glob.glob(os.path.join(RECIPES_DIR, "*.json"))):
        fname = os.path.basename(path)
        with open(path) as f:
            try:
                r = json.load(f)
            except json.JSONDecodeError as e:
                fail("%s: %s" % (fname, e))
        unknown = set(r) - RECIPE_KEYS
        if unknown:
            fail("%s: unknown keys %s" % (fname, sorted(unknown)))
        if ("pattern" in r) == ("ingredients" in r):
            fail("%s: need exactly one of \"pattern\" or \"ingredients\"" % fname)
        if "result" not in r or not isinstance(r["result"], str):
            fail("%s: result must be a block or item name" % fname)
        result = resolve_name(r["result"], fname)
        max_stack = 64 if result < LAST_BLOCK_ID else items[result].get("max_stack", 64)
        count = r.get("count", 1)
        if not isinstance(count, int) or not (1 <= count <= max_stack):
            fail("%s: bad count %r (need 1-%d)" % (fname, count, max_stack))
        cells = [None] * 9
        if "pattern" in r:
            pattern = r["pattern"]
            if (not isinstance(pattern, list) or not (1 <= len(pattern) <= 3) or
                    any(not isinstance(row, str) or not (1 <= len(row) <= 3) for row in pattern) or
                    len({len(row) for row in pattern}) != 1):
                fail("%s: pattern must be 1-3 rows, all the same length (<=3 chars)" % fname)
            key = r.get("key")
            if not isinstance(key, dict):
                fail("%s: shaped recipe needs a key object" % fname)
            used = {ch for row in pattern for ch in row if ch != " "}
            for k in key:
                if not isinstance(k, str) or len(k) != 1 or k == " ":
                    fail("%s: key entries must be single non-space characters" % fname)
            if set(key) != used:
                fail("%s: key must cover exactly the pattern characters %s" % (fname, sorted(used)))
            w, h = len(pattern[0]), len(pattern)
            for y, row in enumerate(pattern):
                for x, ch in enumerate(row):
                    if ch != " ":
                        cells[y * w + x] = ingredient_ids(key[ch], fname)
            shaped, width, height = True, w, h
        else:
            ingredients = r["ingredients"]
            if not isinstance(ingredients, list) or not (1 <= len(ingredients) <= 9):
                fail("%s: ingredients must be a list of 1-9 entries" % fname)
            for i, ing in enumerate(ingredients):
                cells[i] = ingredient_ids(ing, fname)
            shaped, width, height = False, 0, 0
        recipes.append({"shaped": shaped, "width": width, "height": height,
                        "cells": cells, "result": result, "count": count,
                        "_file": fname})
    return recipes


def emit_recipes(recipes, blocks, items):
    """src/common/recipes_gen.inc — option arrays (RECIPE_OPTS_<n>, deduped
    by first use) then CRAFT_RECIPES entries with cells packed dense
    (shaped: row-major within width, width*height used; shapeless: first
    n cells)."""
    def id_name(iid):
        return blocks[iid]["name"] if iid < LAST_BLOCK_ID else items[iid]["name"]

    out = [HEADER]
    opt_arrays = {}

    def opt_array(ids):
        key = tuple(ids)
        if key not in opt_arrays:
            opt_arrays[key] = len(opt_arrays)
        return "RECIPE_OPTS_%d" % opt_arrays[key]

    entries = []
    for rec in recipes:
        cells_code = []
        for ids in rec["cells"]:
            if ids is None:
                cells_code.append("{ nullptr, 0 }")
            else:
                cells_code.append("{ %s, %d }" % (opt_array(ids), len(ids)))
        entries.append("    { %d, %d, %d, { %s }, %s, %d },\n" %
                       (1 if rec["shaped"] else 0, rec["width"], rec["height"],
                        ", ".join(cells_code), id_name(rec["result"]), rec["count"]))
    for key in sorted(opt_arrays, key=opt_arrays.get):
        out.append("static const ItemID %s[] = { %s };\n" %
                   (opt_array(key), ", ".join(id_name(i) for i in key)))
    out.append("\nconst CraftRecipe CRAFT_RECIPES[] = {\n")
    out.extend(entries)
    out.append("};\n")
    with open(OUT_RECIPES, "w") as f:
        f.writelines(out)


def resolve_faces(name, b):
    """JSON textures dict -> per-face texture name list (FACE_* order)."""
    tex = b.get("textures", {})
    unknown = set(tex) - (set(FACE_KEYS) | {"all", "side"})
    if unknown:
        fail("%s: unknown texture face keys %s" % (b["_file"], sorted(unknown)))
    for k, v in tex.items():
        if not isinstance(v, str):
            fail("%s: texture %s must be a name string" % (b["_file"], k))
    faces = {k: name for k in FACE_KEYS}
    if "all" in tex:
        faces = {k: tex["all"] for k in FACE_KEYS}
    if "side" in tex:
        for k in SIDE_FACES:
            faces[k] = tex["side"]
    for k in FACE_KEYS:
        if k in tex:
            faces[k] = tex[k]
    return [faces[k] for k in FACE_KEYS]


def find_image_path(src, name, what="texture"):
    """Resolve a texture source spec (or bare texture name) to a file path."""
    candidates = []
    if src:
        if src.endswith((".png", ".tga")):
            candidates.append(os.path.join(BEDROCK_SAMPLES, src))
        elif "/" in src:
            # Resource-pack-relative path without extension (e.g.
            # textures/blocks/planks_birch).
            candidates += [
                os.path.join(BEDROCK_SAMPLES, src + ".png"),
                os.path.join(BEDROCK_SAMPLES, src + ".tga"),
            ]
        else:
            candidates += [
                os.path.join(TEXTURES_DIR, src + ".png"),
                os.path.join(BEDROCK_SAMPLES, "textures", "blocks", src + ".png"),
                os.path.join(BEDROCK_SAMPLES, "textures", "blocks", src + ".tga"),
                os.path.join(BEDROCK_SAMPLES, "textures", "items", src + ".png"),
            ]
    else:
        candidates = [
            os.path.join(TEXTURES_DIR, name + ".png"),
            os.path.join(BEDROCK_SAMPLES, "textures", "blocks", name + ".png"),
            os.path.join(BEDROCK_SAMPLES, "textures", "blocks", name + ".tga"),
            os.path.join(BEDROCK_SAMPLES, "textures", "items", name + ".png"),
        ]
    path = next((c for c in candidates if os.path.exists(c)), None)
    if not path:
        fail("%s %r: no image found (tried %s). If the source lives in "
             "bedrock-samples, run `make bedrock-samples` or set BEDROCK_SAMPLES" %
             (what, src or name, [os.path.relpath(c, ROOT) for c in candidates]))
    return path


def apply_tint(img, tint, name):
    if not re.match(r"^#[0-9a-fA-F]{6}$", tint):
        fail("texture %r: bad tint %r" % (name, tint))
    tr, tg, tb = int(tint[1:3], 16), int(tint[3:5], 16), int(tint[5:7], 16)
    r, g, b_, a = img.split()
    lut_r = [min(255, (i * tr) // 255) for i in range(256)]
    lut_g = [min(255, (i * tg) // 255) for i in range(256)]
    lut_b = [min(255, (i * tb) // 255) for i in range(256)]
    return Image.merge("RGBA", (r.point(lut_r), g.point(lut_g), b_.point(lut_b), a))


def resolve_image(name, meta):
    """Find the source image for a texture, apply frame crop + tint."""
    src = meta.get("source")
    path = find_image_path(src, name)
    img = Image.open(path).convert("RGBA")
    frame = meta.get("frame", 0)
    if not isinstance(frame, int) or frame < 0:
        fail("texture %r: bad frame %r" % (name, frame))
    img = img.crop((0, frame * TILE, TILE, (frame + 1) * TILE))
    if img.size != (TILE, TILE):
        fail("texture %r (%s): not %dx%d after frame crop (is %s)" % (name, os.path.relpath(path, ROOT), TILE, TILE, img.size))
    tint = meta.get("tint")
    if tint is not None:
        img = apply_tint(img, tint, name)
    alpha = meta.get("alpha")
    if alpha is not None:
        if not isinstance(alpha, int) or not (0 <= alpha <= 255):
            fail("texture %r: bad alpha %r (need 0-255)" % (name, alpha))
        r, g, b_, a = img.split()
        img = Image.merge("RGBA", (r, g, b_, a.point(lambda v: alpha if v else 0)))
    overlay = meta.get("overlay")
    if overlay is not None:
        # A second (typically grayscale) tile alpha-composited over the base —
        # e.g. the grass fringe over dirt. Optional tint applies to the
        # overlay only.
        if not isinstance(overlay, dict) or set(overlay) - {"source", "tint", "frame"}:
            fail("texture %r: overlay must be {source, tint?, frame?}" % name)
        opath = find_image_path(overlay.get("source"), name, "overlay")
        ov = Image.open(opath).convert("RGBA")
        oframe = overlay.get("frame", 0)
        if not isinstance(oframe, int) or oframe < 0:
            fail("texture %r overlay: bad frame %r" % (name, oframe))
        ov = ov.crop((0, oframe * TILE, TILE, (oframe + 1) * TILE))
        if ov.size != (TILE, TILE):
            fail("texture %r overlay (%s): not %dx%d" % (name, os.path.relpath(opath, ROOT), TILE, TILE))
        otint = overlay.get("tint")
        if otint is not None:
            ov = apply_tint(ov, otint, name)
        img = Image.alpha_composite(img, ov)
    extract = meta.get("extract")
    if extract is not None:
        # {from: [x, y], size: [w, h], to: [x, y]} — blit a rect of the
        # resolved tile onto a fresh transparent tile. Torch top/bottom
        # faces sample the window that tracks the cuboid's x/z position
        # (cols/rows 7-8 for the 2-wide stick), not the spot where the
        # sprite paints the cap or base; extract copies it there.
        if not isinstance(extract, dict) or set(extract) != {"from", "size", "to"}:
            fail("texture %r: extract must be {from, size, to}" % name)
        fr, sz, to = extract["from"], extract["size"], extract["to"]
        if any(not isinstance(v, list) or len(v) != 2 or
               not all(isinstance(i, int) for i in v) for v in (fr, sz, to)):
            fail("texture %r: extract from/size/to must be [x, y] int pairs" % name)
        if not (0 <= fr[0] and 0 <= fr[1] and sz[0] > 0 and sz[1] > 0 and
                fr[0] + sz[0] <= TILE and fr[1] + sz[1] <= TILE and
                0 <= to[0] and 0 <= to[1] and
                to[0] + sz[0] <= TILE and to[1] + sz[1] <= TILE):
            fail("texture %r: extract rect out of bounds" % name)
        out = Image.new("RGBA", (TILE, TILE), (0, 0, 0, 0))
        out.paste(img.crop((fr[0], fr[1], fr[0] + sz[0], fr[1] + sz[1])), tuple(to))
        img = out
    return img


def main():
    if not os.path.isdir(BEDROCK_SAMPLES):
        fail("BEDROCK_SAMPLES %r does not exist - run `make bedrock-samples` "
             "or set BEDROCK_SAMPLES to a resource_pack directory" % BEDROCK_SAMPLES)
    blocks = load_blocks()
    block_names = {b["name"]: bid for bid, b in blocks.items()}
    for b in blocks.values():
        for a in b.get("aliases", []):
            block_names.setdefault(a, b["id"])
    items, item_names = load_items(block_names)

    # Resolve drops "item" names to ids (block name -> block item id, item
    # name -> ITEM_ID_BASE+ id).
    for bid, b in blocks.items():
        for d in b.get("drops", []):
            iid = block_names.get(d["item"])
            if iid is None:
                iid = item_names.get(d["item"])
            if iid is None:
                fail("%s: drops item %r is not a block or item name" % (b["_file"], d["item"]))
            d["_id"] = iid

    emit_recipes(load_recipes(load_item_tags(block_names, item_names), blocks, items), blocks, items)

    tex_meta = {}
    if os.path.exists(TEXTURES_JSON):
        with open(TEXTURES_JSON) as f:
            tex_meta = json.load(f)
        for name, m in tex_meta.items():
            if not isinstance(m, dict):
                fail("textures.json: %r must map to an object" % name)
            unknown = set(m) - TEX_META_KEYS
            if unknown:
                fail("textures.json: %r has unknown keys %s" % (name, sorted(unknown)))

    # Resolve every block's faces + icon and collect the referenced textures.
    resolved = {}  # bid -> {"faces": [6 names], "icon": name}
    used = set()
    for bid, b in sorted(blocks.items()):
        name = b["name"].lower()
        faces = resolve_faces(name, b)
        # No explicit icon: flat icons face the viewer, so the front texture
        # is the natural default; floor decals like redstone wire have air
        # sides and keep the top face. Isometric icons are drawn from the
        # faces and ignore icon_texture, so top is fine there.
        if not b.get("icon_is_isometric", True):
            front = faces[FACE_KEYS.index("front")]
            icon = faces[FACE_KEYS.index("top")] if front == "air" else front
        else:
            icon = faces[FACE_KEYS.index("top")]
        icon = b.get("icon", icon)
        if "icon" in b and "icon_is_isometric" not in b:
            b["icon_is_isometric"] = False
        resolved[bid] = {"faces": faces, "icon": icon}
        used.update(faces)
        used.add(icon)
    # Item icons are packed into the same atlas.
    for iid, it in sorted(items.items()):
        used.add(it["icon"])
    for name, m in tex_meta.items():
        if m.get("keep"):
            used.add(name)

    # Resolve every texture once (frame/tint/alpha applied), then collapse
    # byte-identical tiles into a single layer. The canonical name is the
    # alphabetically first member; other names still get TEX_* defines.
    images = {}
    for name in sorted(used):
        images[name] = resolve_image(name, tex_meta.get(name, {}))

    # Silhouette (mask) shapes: the 4 side faces become generated
    # <face_tex>__<shape> tiles — the fully resolved face image (frame/tint/
    # alpha already applied) with masked-out pixels set to transparent black.
    # Top and bottom keep the plain material texture. The generated tiles
    # merge like any other byte-identical texture.
    # Model shapes keep every plain face; the same generated tile is made
    # from the side texture and used only as the flat inventory icon, so the
    # icon still shows the silhouette.
    def masked_tile(src, shape, mask):
        mname = "%s__%s" % (src, shape)
        if mname not in images:
            img = images[src].copy()
            px = img.load()
            for r in range(TILE):
                mrow = mask[r]
                for c in range(TILE):
                    if mrow[c] == ".":
                        px[c, r] = (0, 0, 0, 0)
            images[mname] = img
        used.add(mname)
        return mname

    side_idx = [FACE_KEYS.index(k) for k in SIDE_FACES]
    for bid, b in sorted(blocks.items()):
        shape = b.get("shape")
        if shape in SHAPES["masks"]:
            mask = SHAPES["masks"][shape]
            faces = resolved[bid]["faces"]
            for i in side_idx:
                faces[i] = masked_tile(faces[i], shape, mask)
        elif shape in SHAPES["models"]:
            model = SHAPES["models"][shape]
            if "icon_mask" in model and "icon" not in b:
                src = resolved[bid]["faces"][FACE_KEYS.index("front")]
                resolved[bid]["icon"] = masked_tile(src, shape, model["icon_mask"])
                b.setdefault("icon_is_isometric", False)

    canon_members = {}  # canonical name -> [member names]
    for name in sorted(images):
        key = images[name].tobytes()
        canon_members.setdefault(key, []).append(name)
    members = {}
    canonical = {}  # name -> canonical
    for names in canon_members.values():
        canon = min(names)
        members[canon] = names
        for n in names:
            canonical[n] = canon
    canonical_names = sorted(members)

    # Layer order: rotatable layers first (a layer is rotatable if ANY member
    # has random_rotate), then the rest; sorted by canonical name.
    rotatable_canon = sorted(
        c for c in canonical_names
        if any(tex_meta.get(n, {}).get("random_rotate") for n in members[c]))
    rest_canon = sorted(set(canonical_names) - set(rotatable_canon))
    layer_order = rotatable_canon + rest_canon
    layers = {}
    for i, canon in enumerate(layer_order):
        for n in members[canon]:
            layers[n] = i
    count = len(layer_order)
    merged_count = len(used) - count
    # Merged sets mixing rotatable and non-rotatable members: the non-rotatable
    # members now ride the rotatable layer — flag for review.
    mixed_rotatable = [(c, members[c]) for c in rotatable_canon
                       if not all(tex_meta.get(n, {}).get("random_rotate")
                                  for n in members[c])]
    if count > TEXTURE_COUNT_MAX:
        fail("TEXTURE_COUNT %d exceeds %d (GLES texture-array limit)" %
             (count, TEXTURE_COUNT_MAX))
    rows = math.ceil(count / ACROSS)

    # Pack the atlas.
    atlas = Image.new("RGBA", (ACROSS * TILE, rows * TILE), (0, 0, 0, 0))
    for i, canon in enumerate(layer_order):
        atlas.paste(images[canon], ((i % ACROSS) * TILE, (i // ACROSS) * TILE))
    atlas.save(OUT_PNG)

    # include/common/block_ids_gen.hpp
    out = [HEADER, "#pragma once\n\n", "typedef enum {\n"]
    for bid, b in sorted(blocks.items()):
        names = [b["name"]] + b.get("aliases", [])
        for n in names:
            out.append("    %s = %d,\n" % (n, bid))
    out.append("\n    LAST_BLOCK_ID = %d,\n" % LAST_BLOCK_ID)
    out.append("} BlockID;\n\n")
    # Bitset marking which ids have a definition; used to sanitize saved
    # inventory slots whose ids were freed (filler/texture-only) and never
    # redefined.
    out.append("#define BLOCK_DEFINED_BITS_LEN %d\n" % ((LAST_BLOCK_ID + 7) // 8))
    out.append("static const unsigned char BLOCK_DEFINED_BITS[BLOCK_DEFINED_BITS_LEN] = {\n")
    for i in range(0, LAST_BLOCK_ID, 8):
        byte = 0
        for bit in range(8):
            if i + bit in blocks:
                byte |= 1 << bit
        out.append("0x%02x," % byte)
    out.append("\n};\n")
    out.append("static inline int block_id_defined( unsigned int id ) {\n")
    out.append("    return id < (unsigned int)LAST_BLOCK_ID && ( BLOCK_DEFINED_BITS[ id >> 3 ] & ( 1u << ( id & 7 ) ) ) != 0;\n")
    out.append("}\n")
    with open(OUT_IDS, "w") as f:
        f.writelines(out)

    # include/common/item_ids_gen.hpp — pure-item enum (block items keep the
    # BlockID value) + a bitset marking defined item ids.
    out = [HEADER, "#pragma once\n\n", "typedef enum {\n"]
    for iid, it in sorted(items.items()):
        names = [it["name"]] + it.get("aliases", [])
        for n in names:
            out.append("    %s = %d,\n" % (n, iid))
    out.append("\n    ITEM_ID_BASE = %d,\n" % ITEM_ID_BASE)
    item_id_end = max(items) + 1 if items else ITEM_ID_BASE
    out.append("    ITEM_ID_END = %d,\n" % item_id_end)
    out.append("} ItemEnum;\n\n")
    out.append("#define ITEM_DEFINED_BITS_LEN %d\n" % ((item_id_end - ITEM_ID_BASE + 7) // 8))
    out.append("static const unsigned char ITEM_DEFINED_BITS[ITEM_DEFINED_BITS_LEN] = {\n")
    for i in range(0, item_id_end - ITEM_ID_BASE, 8):
        byte = 0
        for bit in range(8):
            if ITEM_ID_BASE + i + bit in items:
                byte |= 1 << bit
        out.append("0x%02x," % byte)
    out.append("\n};\n")
    out.append("static inline int item_id_defined( unsigned int id ) {\n")
    out.append("    return id >= (unsigned int)ITEM_ID_BASE && id < (unsigned int)ITEM_ID_END && ( ITEM_DEFINED_BITS[ ( id - ITEM_ID_BASE ) >> 3 ] & ( 1u << ( ( id - ITEM_ID_BASE ) & 7 ) ) ) != 0;\n")
    out.append("}\n")
    with open(OUT_ITEM_IDS, "w") as f:
        f.writelines(out)

    # src/common/item_definitions_gen.inc — icon layer + max stack per item,
    # indexed by id - ITEM_ID_BASE.
    out = [HEADER]
    for iid in range(ITEM_ID_BASE, item_id_end):
        it = items.get(iid)
        if it is None:
            out.append("    { TEX_AIR, 0 },\n")
            continue
        out.append("    { TEX_%s, %d },\n" % (it["icon"].upper(), it.get("max_stack", 64)))
    with open(OUT_ITEM_INC, "w") as f:
        f.writelines(out)

    # src/common/item_names_gen.inc — per-item name table.
    out = [HEADER]
    for iid in range(ITEM_ID_BASE, item_id_end):
        it = items.get(iid)
        out.append('    "%s",\n' % it["name"] if it else "    nullptr,\n")
    with open(OUT_ITEM_NAMES, "w") as f:
        f.writelines(out)

    # src/common/block_drops_gen.inc — flat drop entries plus a sorted
    # (id, offset, count) lookup table. Blocks with no "drops" key are not in
    # the table and keep the default drop (the block itself).
    out = [HEADER]
    drop_blocks = sorted(bid for bid, b in blocks.items() if "drops" in b)
    flat = []
    for bid in drop_blocks:
        for d in blocks[bid]["drops"]:
            flat.append((d["_id"], d["min"], d["max"], d["chance"]))
    out.append("static const BlockDropGen BLOCK_DROP_ENTRIES[] = {\n")
    for iid, mn, mx, ch in flat:
        iname = None
        if iid < LAST_BLOCK_ID:
            iname = blocks[iid]["name"]
        else:
            iname = items[iid]["name"]
        out.append("    { %s, %d, %d, %sf },\n" % (iname, mn, mx, fmt_float(ch)))
    out.append("};\n\n")
    out.append("static const BlockDropTableGen BLOCK_DROP_TABLE[] = {\n")
    off = 0
    for bid in drop_blocks:
        b = blocks[bid]
        out.append("    { %s, %d, %d },\n" % (b["name"], off, len(b["drops"])))
        off += len(b["drops"])
    out.append("};\n")
    with open(OUT_DROPS, "w") as f:
        f.writelines(out)

    # include/common/texture_ids_gen.hpp — #define only, safe for the GLSL
    # preprocessor (gcc -E -I include).
    # src/common/block_names_gen.inc — name table, nullptr for undefined ids.
    out_names = os.path.join(OUT_DIR, "block_names_gen.inc") if OUT_DIR else \
        os.path.join(ROOT, "src", "common", "block_names_gen.inc")
    out = [HEADER]
    for bid in range(LAST_BLOCK_ID):
        b = blocks.get(bid)
        out.append('    "%s",\n' % b["name"] if b else "    nullptr,\n")
    with open(out_names, "w") as f:
        f.writelines(out)

    # src/common/texture_names_gen.inc — canonical name per layer.
    out_tnames = os.path.join(OUT_DIR, "texture_names_gen.inc") if OUT_DIR else \
        os.path.join(ROOT, "src", "common", "texture_names_gen.inc")
    out = [HEADER]
    for canon in layer_order:
        out.append('    "%s",\n' % canon)
    with open(out_tnames, "w") as f:
        f.writelines(out)

    out = [HEADER, "#ifndef REPGAME_TEXTURE_IDS_GEN_HPP\n#define REPGAME_TEXTURE_IDS_GEN_HPP\n\n"]
    for name in sorted(layers):
        canon = canonical[name]
        if canon != name:
            out.append("#define TEX_%s TEX_%s\n" % (name.upper(), canon.upper()))
        else:
            out.append("#define TEX_%s %d\n" % (name.upper(), layers[name]))
    out.append("\n#define TEXTURE_COUNT %d\n" % count)
    out.append("#define TEXTURE_ROTATABLE_COUNT %d\n" % len(rotatable_canon))
    out.append("#define BLOCK_TEXTURE_ATLAS_ROWS %d\n" % rows)
    out.append("\n#endif\n")
    with open(OUT_TEX, "w") as f:
        f.writelines(out)

    # src/common/block_definitions_gen.inc — all 6 textures + icon for every
    # block, then non-default fields.
    out = [HEADER]
    for bid in range(LAST_BLOCK_ID):
        b = blocks.get(bid)
        if b is None:
            out.append("\n// undefined (%d)\n" % bid)
            for face in FACE_KEYS:
                out.append("block_definitions[ %d ].textures[ %s ] = TEX_AIR;\n" % (bid, FACE_CONST[face]))
            out.append("block_definitions[ %d ].icon_texture = TEX_AIR;\n" % bid)
            out.append("block_definitions[ %d ].is_pickable = false;\n" % bid)
            continue
        r = resolved[bid]
        out.append("\n// %s (%d)\n" % (b["name"], bid))
        for face in FACE_KEYS:
            out.append("block_definitions[ %d ].textures[ %s ] = TEX_%s;\n" % (bid, FACE_CONST[face], r["faces"][FACE_KEYS.index(face)].upper()))
        out.append("block_definitions[ %d ].icon_texture = TEX_%s;\n" % (bid, r["icon"].upper()))
        for key in sorted(b):
            if key in {"_file", "id", "name", "aliases", "textures", "icon", "shape", "creative", "drops"}:
                continue
            val = b[key]
            prefix = "block_definitions[ %d ]." % bid
            if key == "render_order":
                out.append("%srenderOrder = RenderOrder_%s;\n" % (prefix, val))
            elif key == "needs_place_on_any_solid":
                for face in FACE_KEYS:
                    if val.get(face):
                        out.append("%sneeds_place_on_any_solid[ %s ] = true;\n" % (prefix, FACE_CONST[face]))
            elif key in VEC3_SHORT:
                out.append("%s%s = { %s };\n" % (prefix, key, ", ".join(str(int(x)) for x in val)))
            elif key in VEC3_BOOL:
                out.append("%s%s = { %s };\n" % (prefix, key, ", ".join("true" if x else "false" for x in val)))
            elif key in BLOCK_REF_FIELDS:
                out.append("%s%s = %s;\n" % (prefix, key, val))
            elif key in BOOL_FIELDS:
                out.append("%s%s = %s;\n" % (prefix, key, "true" if val else "false"))
            elif key in FLOAT_FIELDS:
                out.append("%s%s = %sf;\n" % (prefix, key, fmt_float(val)))
            else:
                out.append("%s%s = %s;\n" % (prefix, key, val))
    with open(OUT_INC, "w") as f:
        f.writelines(out)

    # include/common/creative_order_gen.hpp + human-readable report.
    kept_ids = set()
    if os.path.exists(KEPT_IDS_FILE):
        kept_ids = {int(l) for l in open(KEPT_IDS_FILE) if l.strip()}
    creative, hidden = compute_creative(blocks, resolved, kept_ids, layers)
    out_cre = os.path.join(OUT_DIR, "creative_order_gen.hpp") if OUT_DIR else \
        os.path.join(ROOT, "include", "common", "creative_order_gen.hpp")
    out = [HEADER, "#pragma once\n\n#include \"common/item.hpp\"\n\n"]
    out.append("#define CREATIVE_BLOCK_COUNT %d\n" % (len(creative) + len(items)))
    out.append("static const ItemID CREATIVE_BLOCKS[CREATIVE_BLOCK_COUNT] = {\n")
    for bid in creative:
        out.append("    %s,\n" % blocks[bid]["name"])
    for iid, it in sorted(items.items()):
        out.append("    %s,\n" % it["name"])
    out.append("};\n")
    with open(out_cre, "w") as f:
        f.writelines(out)
    rep_lines = []
    for bid in creative:
        dups = ", ".join(blocks[h]["name"] for h in hidden.get(bid, []))
        mat, _dye = material_key(blocks[bid]["name"])
        rep_lines.append("%s\t%s\t%d\thidden duplicates: %s\n" %
                         (mat, blocks[bid]["name"], bid, dups or "-"))
    os.makedirs(os.path.dirname(CREATIVE_REPORT), exist_ok=True)
    with open(CREATIVE_REPORT, "w") as f:
        f.write("material\tname\tid\thidden duplicates\n")
        f.writelines(rep_lines)

    print("blocks_import: %d blocks, %d textures (%d rotatable), atlas %dx%d -> %s" %
          (len(blocks), count, len(rotatable_canon), atlas.width, atlas.height,
           ", ".join(os.path.relpath(p, ROOT) for p in (OUT_IDS, OUT_ITEM_IDS, OUT_TEX, OUT_INC, OUT_ITEM_INC, OUT_ITEM_NAMES, OUT_DROPS, OUT_RECIPES, OUT_PNG))))
    pickable = sum(1 for b in blocks.values() if b.get("is_pickable", True))
    hidden_n = sum(len(v) for v in hidden.values())
    print("blocks_import: creative %d listed of %d pickable (%d hidden duplicates) -> %s" %
          (len(creative), pickable, hidden_n, os.path.relpath(out_cre, ROOT)))
    if merged_count:
        print("blocks_import: %d textures merged into existing layers by identical pixels" % merged_count)
    for canon, names in mixed_rotatable:
        print("blocks_import: WARNING rotatable layer %s merges non-rotatable %s" %
              (canon, [n for n in names if not tex_meta.get(n, {}).get("random_rotate")]))


if __name__ == "__main__":
    main()
