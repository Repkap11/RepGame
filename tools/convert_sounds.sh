#!/bin/bash
# Sound asset pipeline for RepGame. Driven by tools/sounds_manifest.txt
# (name|source|type|title — see the manifest header).
#
#   convert_sounds.sh convert <name> [outdir]  -> <outdir>/<name>.ogg via ffmpeg
#   convert_sounds.sh convert-all [outdir]     -> all manifest entries (prebuilt)
#   convert_sounds.sh gen [path]               -> generated C++ tables header
#
# convert needs ffmpeg on PATH; gen is pure text and runs in the flatpak
# sandbox where ffmpeg is unavailable.
set -euo pipefail
cd "$(dirname "$0")/.."
MANIFEST=tools/sounds_manifest.txt

manifest_line() {
    awk -F'|' -v n="$1" '!/^[[:space:]]*(#|$)/ && $1 == n { print; exit }' "$MANIFEST"
}

manifest_names() {
    awk -F'|' '!/^[[:space:]]*(#|$)/ { print $1 }' "$MANIFEST"
}

case "${1:-}" in
    convert)
        name="$2"
        outdir="${3:-out/sounds}"
        line=$(manifest_line "$name")
        if [ -z "$line" ]; then
            echo "convert_sounds.sh: no manifest entry for '$name'" >&2
            exit 1
        fi
        src="sounds/$(echo "$line" | cut -d'|' -f2)"
        type=$(echo "$line" | cut -d'|' -f3)
        if [ ! -f "$src" ]; then
            echo "convert_sounds.sh: missing source '$src'" >&2
            exit 1
        fi
        quality=3
        [ "$type" = sfx ] && quality=4
        mkdir -p "$outdir"
        ffmpeg -y -v error -i "$src" -vn -map_metadata -1 -q:a "$quality" "$outdir/$name.ogg"
        ;;
    convert-all)
        outdir="${2:-prebuilt/sounds}"
        for name in $(manifest_names); do
            "$0" convert "$name" "$outdir"
        done
        ;;
    gen)
        out="${2:-out/include/sounds_manifest.hpp}"
        mkdir -p "$(dirname "$out")"
        {
            echo '#pragma once'
            echo '// Generated by tools/convert_sounds.sh gen from tools/sounds_manifest.txt - do not edit.'
            echo '#include "binary_blobs.hpp"'
            echo '#ifdef REPGAME_AUDIO'
            awk -F'|' '!/^[[:space:]]*(#|$)/ { printf "MK_BLOB( out_sounds, %s, ogg );\n", $1 }' "$MANIFEST"
            echo 'typedef struct {'
            echo '    const BinaryBlob *blob;'
            echo '    const char *title;'
            echo '} MusicTrackEntry;'
            echo 'static const MusicTrackEntry MUSIC_TRACKS[] = {'
            awk -F'|' '!/^[[:space:]]*(#|$)/ && $3 == "music" { printf "    { &%s, \"%s\" },\n", $1, $4 }' "$MANIFEST"
            echo '    { NULL, NULL },'
            echo '};'
            echo 'typedef struct {'
            echo '    const char *base;'
            echo '    const BinaryBlob *blob;'
            echo '} SfxEntry;'
            echo 'static const SfxEntry SFX_SOUNDS[] = {'
            awk -F'|' '!/^[[:space:]]*(#|$)/ && $3 == "sfx" { n = $1; sub(/_[0-9]+$/, "", n); printf "    { \"%s\", &%s },\n", n, $1 }' "$MANIFEST"
            echo '    { NULL, NULL },'
            echo '};'
            echo '#endif'
        } >"$out"
        ;;
    *)
        echo "usage: $0 convert <name> [outdir] | convert-all [outdir] | gen [path]" >&2
        exit 1
        ;;
esac
