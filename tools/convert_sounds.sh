#!/bin/bash
# Sound asset pipeline for RepGame. Driven by tools/sounds_manifest.txt
# (name|source|type|title — see the manifest header).
#
#   convert_sounds.sh convert <name> [outdir]  -> <outdir>/<name>.ogg via ffmpeg
#   convert_sounds.sh convert-all [outdir]     -> all manifest entries (prebuilt)
#   convert_sounds.sh gen [path]               -> generated C++ tables header
#
# convert needs ffmpeg on PATH; gen is pure text and runs in the flatpak
# sandbox where ffmpeg is unavailable.
set -euo pipefail
cd "$(dirname "$0")/.."
MANIFEST=tools/sounds_manifest.txt

manifest_line() {
    awk -F'|' -v n="$1" '!/^[[:space:]]*(#|$)/ && $1 == n { print; exit }' "$MANIFEST"
}

manifest_names() {
    awk -F'|' '!/^[[:space:]]*(#|$)/ { print $1 }' "$MANIFEST"
}

case "${1:-}" in
    convert)
        name="$2"
        outdir="${3:-out/sounds}"
        line=$(manifest_line "$name")
        if [ -z "$line" ]; then
            echo "convert_sounds.sh: no manifest entry for '$name'" >&2
            exit 1
        fi
        src="sounds/$(echo "$line" | cut -d'|' -f2)"
        type=$(echo "$line" | cut -d'|' -f3)
        if [ ! -f "$src" ]; then
            echo "convert_sounds.sh: missing source '$src'" >&2
            exit 1
        fi
        quality=3
        [ "$type" = sfx ] && quality=4
        mkdir -p "$outdir"
        # The pack's recordings span ~20dB between pools (gravel steps are
        # way hotter than grass). Normalize step_* and dig_* clips to a
        # shared loudness target via volumedetect's mean volume, clamped so
        # the gain never pushes the peak past -1.5dBFS.
        af=()
        target=""
        case "$name" in
            step_*) target=-40 ;;
            dig_*) target=-30 ;;
            swim_*) target=-36 ;;
            splash_* | heavy_splash) target=-30 ;;
        esac
        if [ -n "$target" ]; then
            stats=$(ffmpeg -v info -i "$src" -af volumedetect -f null - 2>&1 || true)
            mean=$(echo "$stats" | awk '/mean_volume/ { print $5 }')
            peak=$(echo "$stats" | awk '/max_volume/ { print $5 }')
            gain=$(awk -v t="$target" -v m="${mean:-0}" -v p="${peak:-0}" \
                'BEGIN { g = t - m; lim = -1.5 - p; if ( g > lim ) g = lim; printf "%.2f", g }')
            af=( -af "volume=${gain}dB" )
        fi
        ffmpeg -y -v error -i "$src" -vn -map_metadata -1 "${af[@]}" -q:a "$quality" "$outdir/$name.ogg"
        ;;
    convert-all)
        outdir="${2:-prebuilt/sounds}"
        for name in $(manifest_names); do
            "$0" convert "$name" "$outdir"
        done
        ;;
    gen)
        out="${2:-out/include/sounds_manifest.hpp}"
        mkdir -p "$(dirname "$out")"
        {
            echo '#pragma once'
            echo '// Generated by tools/convert_sounds.sh gen from tools/sounds_manifest.txt - do not edit.'
            echo '#include "binary_blobs.hpp"'
            echo '#ifdef REPGAME_AUDIO'
            echo '#if defined( REPGAME_WASM )'
            echo '// WASM has no MK_BLOB embedding — the .ogg files ship in the WASMFS'
            echo '// preload (out/wasm/fs/sounds/) and the tables carry their paths.'
            echo 'typedef struct {'
            echo '    const char *path;'
            echo '    const char *title;'
            echo '} MusicTrackEntry;'
            echo 'static const MusicTrackEntry MUSIC_TRACKS[] = {'
            awk -F'|' '!/^[[:space:]]*(#|$)/ && $3 == "music" { printf "    { \"sounds/%s.ogg\", \"%s\" },\n", $1, $4 }' "$MANIFEST"
            echo '    { NULL, NULL },'
            echo '};'
            echo 'typedef struct {'
            echo '    const char *base;'
            echo '    const char *path;'
            echo '} SfxEntry;'
            echo 'static const SfxEntry SFX_SOUNDS[] = {'
            awk -F'|' '!/^[[:space:]]*(#|$)/ && $3 == "sfx" { n = $1; sub(/_[0-9]+$/, "", n); printf "    { \"%s\", \"sounds/%s.ogg\" },\n", n, $1 }' "$MANIFEST"
            echo '    { NULL, NULL },'
            echo '};'
            echo '#else'
            awk -F'|' '!/^[[:space:]]*(#|$)/ { printf "MK_BLOB( out_sounds, %s, ogg );\n", $1 }' "$MANIFEST"
            echo 'typedef struct {'
            echo '    const BinaryBlob *blob;'
            echo '    const char *title;'
            echo '} MusicTrackEntry;'
            echo 'static const MusicTrackEntry MUSIC_TRACKS[] = {'
            awk -F'|' '!/^[[:space:]]*(#|$)/ && $3 == "music" { printf "    { &%s, \"%s\" },\n", $1, $4 }' "$MANIFEST"
            echo '    { NULL, NULL },'
            echo '};'
            echo 'typedef struct {'
            echo '    const char *base;'
            echo '    const BinaryBlob *blob;'
            echo '} SfxEntry;'
            echo 'static const SfxEntry SFX_SOUNDS[] = {'
            awk -F'|' '!/^[[:space:]]*(#|$)/ && $3 == "sfx" { n = $1; sub(/_[0-9]+$/, "", n); printf "    { \"%s\", &%s },\n", n, $1 }' "$MANIFEST"
            echo '    { NULL, NULL },'
            echo '};'
            echo '#endif'
            echo '#endif'
        } >"$out"
        ;;
    *)
        echo "usage: $0 convert <name> [outdir] | convert-all [outdir] | gen [path]" >&2
        exit 1
        ;;
esac
